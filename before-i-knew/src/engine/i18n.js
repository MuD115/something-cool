let settingsRef = null;

export function bindI18n(settings) {
  settingsRef = settings;
}

export function lang() {
  return settingsRef?.get('lang') === 'ar' ? 'ar' : 'en';
}

export function t(key) {
  const l = lang();
  return STR[l][key] ?? STR.en[key] ?? key;
}
